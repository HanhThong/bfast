// The languages a ticket can be written in.
//
// Pure data, no `vscode` import: the settings webview builds its dropdown from
// `LANGUAGES`, and the host validates a hand-edited `bfast.json` against
// `LANGUAGE_CODES` before writing — the same split every other settings module
// follows, so the form and the writer cannot disagree on what a valid value is.
//
// The **code** is what `bfast.json` stores, because it is the stable identifier;
// `name` is looked up only when the prompt is built, since that is the string a
// model actually understands. `native` is for the picker alone.

export interface LanguageOption {
	/** ISO 639-1, lower-case, two letters. */
	code: string;
	/** English name — also the string that goes into the prompt. */
	name: string;
	/** Endonym, shown in the dropdown beside the English name. */
	native: string;
}

