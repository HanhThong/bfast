/** The whitelist `parseAiSettings` and `validateAiSettings` check against. */
export const LANGUAGE_CODES: ReadonlySet<string> = new Set(LANGUAGES.map((lang) => lang.code));

/**
 * The English name for a code, or `undefined` for anything unknown — including
 * `undefined` itself, which is how "no preference" reaches the prompt builder.
 */
export function languageName(code: string | undefined): string | undefined {
	if (typeof code !== 'string') {
		return undefined;
	}
	const wanted = code.trim().toLowerCase();
	return LANGUAGES.find((lang) => lang.code === wanted)?.name;
}
